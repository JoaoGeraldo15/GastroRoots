CREATE TABLE PERMISSION (
    ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    NAME VARCHAR(100) NOT NULL,
    DESCRIPTION VARCHAR(255) NOT NULL
);

CREATE TABLE ROLE (
    ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    NAME VARCHAR(100) NOT NULL
);

CREATE TABLE ROLE_PERMISSION (
    ROLE_ID BIGINT NOT NULL,
    PERMISSION_ID BIGINT NOT NULL,
    PRIMARY KEY (ROLE_ID, PERMISSION_ID),
    CONSTRAINT FK_PERMISSION_ROLE_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLE (ID),
    CONSTRAINT FK_PERMISSION_ROLE_PERMISSION FOREIGN KEY (PERMISSION_ID) REFERENCES PERMISSION (ID)
);

CREATE TABLE USER_ACCOUNT (
    ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    EXTERNAL_ID CHAR(36) NOT NULL,
    NAME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL,
    PASSWORD VARCHAR(255) NOT NULL,
    REGISTRATION_DATE DATETIME NOT NULL
);

CREATE TABLE USER_ACCOUNT_ROLE(
    USER_ACCOUNT_ID BIGINT NOT NULL,
    ROLE_ID BIGINT NOT NULL,
    PRIMARY KEY (USER_ACCOUNT_ID, ROLE_ID),
    CONSTRAINT FK_USER_ACCOUNT_ROLE_USER_ACCOUNT FOREIGN KEY (USER_ACCOUNT_ID) REFERENCES USER_ACCOUNT (ID),
    CONSTRAINT FK_USER_ACCOUNT_ROLE_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLE(ID)
);